def calculate_rms(signal):
    return np.sqrt(np.mean(signal ** 2))


def calculate_zcr(signal):
    crossings = np.sum(
        signal[:-1] * signal[1:] < 0
    )

    duration = len(signal) / SAMPLE_RATE

    return crossings / duration


def calculate_predominant_frequency(signal):
    frequencies, power = welch(
        signal,
        fs=SAMPLE_RATE,
        nperseg=min(512, len(signal))
    )

    if len(power) > 1:
        index = np.argmax(power[1:]) + 1
    else:
        index = np.argmax(power)

    return frequencies[index]


def calculate_sta_lta(signal):
    STA_SECONDS = 0.25
    LTA_SECONDS = 2.0

    STA_SAMPLES = int(STA_SECONDS * SAMPLE_RATE)
    LTA_SAMPLES = int(LTA_SECONDS * SAMPLE_RATE)

    squared = signal ** 2

    sta_values = []

    start = LTA_SAMPLES
    end = len(signal) - STA_SAMPLES

    if end <= start:
        return 0.0

    for i in range(start, end):

        lta_start = i - LTA_SAMPLES
        lta_end = i

        sta_start = i
        sta_end = i + STA_SAMPLES

        lta = np.mean(
            squared[lta_start:lta_end]
        )

        sta = np.mean(
            squared[sta_start:sta_end]
        )

        lta = max(lta, 1e-20)

        ratio = sta / lta

        sta_values.append(ratio)

    if len(sta_values) == 0:
        return 0.0

    return np.max(sta_values)


def extract_channel_features(signal):

    signal = np.asarray(
        signal,
        dtype=np.float64
    )

    return {
        "STA_LTA": calculate_sta_lta(signal),
        "RMS": calculate_rms(signal),
        "ZCR": calculate_zcr(signal),
        "Predominant_Frequency":
            calculate_predominant_frequency(signal)
    }


