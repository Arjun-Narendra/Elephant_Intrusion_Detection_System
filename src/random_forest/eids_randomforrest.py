def load_jsonl_recording(file_path):
    vx_values = []
    vy_values = []
    vz_values = []

    timestamps = []
    skipped_lines = 0

    with open(file_path, "r", errors="replace") as file:
        for line in file:
            try:
                record = json.loads(line)

                if "sample" not in record:
                    continue

                if not all(
                    key in record
                    for key in ["vx", "vy", "vz"]
                ):
                    skipped_lines += 1
                    continue

                vx_values.append(float(record["vx"]))
                vy_values.append(float(record["vy"]))
                vz_values.append(float(record["vz"]))

                timestamps.append(
                    record.get("time", None)
                )

            except Exception:
                skipped_lines += 1

    signals = {
        "CH1": np.array(vx_values),
        "CH2": np.array(vy_values),
        "CH3": np.array(vz_values)
    }

    return signals, timestamps, skipped_lines

# ============================================
# EXTRACT SLIDING-WINDOW FEATURES
# ============================================

def extract_sliding_window_features(
    signals,
    timestamps,
    window_size=2045,
    step_size=200
):
    total_samples = len(signals["CH1"])

    rows = []

    for start in range(
        0,
        total_samples - window_size + 1,
        step_size
    ):

        end = start + window_size

        row = {
            "Start_Sample": start,
            "End_Sample": end,
            "Window_Duration_sec": window_size / SAMPLE_RATE
        }

        # Preserve the first and last timestamp in the window
        if timestamps:
            row["Start_Timestamp"] = timestamps[start]
            row["End_Timestamp"] = timestamps[end - 1]

        for channel in ["CH1", "CH2", "CH3"]:

            signal_window = signals[channel][start:end]

            channel_features = extract_channel_features(
                signal_window
            )

            for feature_name, feature_value in channel_features.items():
                row[f"{channel}_{feature_name}"] = feature_value

        rows.append(row)

    return pd.DataFrame(rows)

