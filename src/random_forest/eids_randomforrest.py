def calculate_sta_lta(signal, sample_rate=200):
    signal = np.asarray(signal, dtype=float)
    signal = signal - np.mean(signal)

    absolute_signal = np.abs(signal)

    sta_size = max(1, int(sample_rate * 1.0))

    sta_values = np.convolve(
        absolute_signal,
        np.ones(sta_size) / sta_size,
        mode="valid"
    )

    lta_value = np.mean(absolute_signal)

    if lta_value == 0:
        return 0.0

    return float(np.max(sta_values) / lta_value)


def calculate_rms(signal):
    signal = np.asarray(signal, dtype=float)
    signal = signal - np.mean(signal)

    return float(np.sqrt(np.mean(signal ** 2)))


def calculate_zcr(signal):
    signal = np.asarray(signal, dtype=float)
    signal = signal - np.mean(signal)

    return float(np.sum(
        np.diff(np.signbit(signal)) != 0
    ))


def calculate_predominant_frequency(signal, sample_rate=200):
    signal = np.asarray(signal, dtype=float)
    signal = signal - np.mean(signal)

    if np.all(signal == 0):
        return 0.0

    frequencies = np.fft.rfftfreq(
        len(signal),
        d=1 / sample_rate
    )

    spectrum = np.abs(np.fft.rfft(signal))
    spectrum[0] = 0

    dominant_index = np.argmax(spectrum)

    return float(frequencies[dominant_index])


def extract_channel_features(signal):
    return {
        "STA_LTA": calculate_sta_lta(signal, SAMPLE_RATE),
        "RMS": calculate_rms(signal),
        "ZCR": calculate_zcr(signal),
        "Predominant_Frequency":
            calculate_predominant_frequency(signal, SAMPLE_RATE)
    }

