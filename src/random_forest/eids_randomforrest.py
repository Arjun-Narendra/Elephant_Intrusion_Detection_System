def process_jsonl(filepath):

    channel_1 = []
    channel_2 = []
    channel_3 = []
    timestamps = []

    with open(filepath, "r") as file:

        for line_number, line in enumerate(file, start=1):

            try:
                record = json.loads(line)

                # Use the same fields as the previous test
                if not all(
                    key in record
                    for key in ["vx", "vy", "vz"]
                ):
                    continue

                channel_1.append(float(record["vx"]))
                channel_2.append(float(record["vy"]))
                channel_3.append(float(record["vz"]))

                timestamps.append(
                    record.get("time", "")
                )

            except Exception as error:
                print(
                    f"Skipping line {line_number}: {error}"
                )

    channels = [
        np.asarray(channel_1),
        np.asarray(channel_2),
        np.asarray(channel_3)
    ]

    results = []

    if len(channel_1) < WINDOW_SIZE:
        print(
            f"{os.path.basename(filepath)}: "
            f"Not enough samples"
        )
        return results

    for start in range(
        0,
        len(channel_1) - WINDOW_SIZE + 1,
        STEP_SIZE
    ):

        end = start + WINDOW_SIZE

        row = {
            "Source_File": os.path.basename(filepath),
            "Start_Sample": start,
            "End_Sample": end - 1,
            "Start_Time": timestamps[start],
            "End_Time": timestamps[end - 1]
        }

        feature_row = {}

        for channel_index, signal in enumerate(channels, start=1):

            window = signal[start:end]

            features = extract_channel_features(window)

            for feature_name, value in features.items():

                column_name = (
                    f"CH{channel_index}_{feature_name}"
                )

                feature_row[column_name] = value

        # Keep only the model's required features
        model_input = pd.DataFrame(
            [feature_row]
        )[selected_features]

        prediction = rf_model.predict(model_input)[0]

        probabilities = rf_model.predict_proba(
            model_input
        )[0]

        confidence = np.max(probabilities)

        row["Prediction"] = prediction
        row["Confidence"] = confidence

        for class_name, probability in zip(
            rf_model.classes_,
            probabilities
        ):
            row[f"Probability_{class_name}"] = probability

        row.update(feature_row)

        results.append(row)

    return results


